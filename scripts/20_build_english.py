"""Build English UI bundles from the reviewed local translation catalogue.

Run after changing Vietnamese UI copy or webapp/i18n/en.tsv. Backend display
vocabulary is included separately; raw data, identifiers and model inputs stay intact.
"""
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "webapp/static"
OUT = STATIC / "en"   # generated, git-ignored


def catalogue():
    result = {}
    for line in (ROOT / "webapp/i18n/en.tsv").read_text(encoding="utf-8-sig").splitlines():
        if line.strip() and not line.startswith("#"):
            vi, en = line.split("\t", 1)
            result[vi] = en
    return result


def vocabulary():
    # Literal evaluation avoids importing ML libraries while building UI assets.
    tree = ast.parse((ROOT / "webapp/zero_shot.py").read_text(encoding="utf-8"))
    out = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            try:
                value = ast.literal_eval(node.value)
            except (ValueError, TypeError):
                continue
            if isinstance(value, list):
                for item in value:
                    if isinstance(item, tuple) and len(item) >= 2 and isinstance(item[1], str):
                        out[item[1]] = item[0]
            elif any(isinstance(t, ast.Name) and t.id == "CATALOGUE_VI" for t in node.targets):
                out.update({v: k for k, v in value.items()})
    tree = ast.parse((ROOT / "webapp/colors.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "NAMED" for t in node.targets):
            out.update({v[0]: v[1] for v in ast.literal_eval(node.value)})
    return out


def translate(source, translations):
    # Match complete words so catalogue aliases never modify JS identifiers.
    alternatives = [(r"(?<!\w)" if k[0].isalnum() else "") + re.escape(k)
                    + (r"(?!\w)" if k[-1].isalnum() else "")
                    for k in sorted(translations, key=len, reverse=True)]
    pattern = re.compile("|".join(alternatives))
    return pattern.sub(lambda m: translations[m.group()], source)


def build():
    ui = catalogue()
    all_terms = {**vocabulary(), **ui}
    all_terms = {k: ui.get(v, v) for k, v in all_terms.items() if "${" not in k}
    # Backend style names use sentence case; keep the same casing in English.
    all_terms = {**{k[:1].upper() + k[1:]: v[:1].upper() + v[1:] for k, v in all_terms.items()}, **all_terms}
    OUT.mkdir(exist_ok=True)
    (OUT / "dictionary.js").write_text(
        "// Generated by scripts/20_build_english.py\nwindow.EN_DICTIONARY = "
        + json.dumps(all_terms, ensure_ascii=False) + ";\n", encoding="utf-8")
    for name in ("manager", "app"):
        source = (STATIC / f"{name}.js").read_text(encoding="utf-8-sig")
        english = translate(source, ui)
        english = english.replace('"vi-VN"', '"en-GB"')
        english = english.replace("return body;", "return I18N.data(body);")
        english = english.replace("new Error(detail)", "new Error(I18N.text(detail))")
        english = english.replace("new Error((body && body.detail)", "new Error((body && I18N.text(body.detail))")
        english = english.replace('const fmt = (d) => `${String(d.getUTCDate()).padStart(2, "0")}/${String(d.getUTCMonth() + 1).padStart(2, "0")}/${d.getUTCFullYear()}`;', 'const fmt = (d) => I18N.date(d);')
        english = english.replace('const fmtShort = (d) => `${String(d.getUTCDate()).padStart(2, "0")}/${String(d.getUTCMonth() + 1).padStart(2, "0")}`;', 'const fmtShort = (d) => I18N.date(d, false);')
        english = english.replace(' + " tr"', ' + "M"')
        # Existing categorical filters retain raw catalogue values.
        english = english.replace('esc(fmtv(v))', 'esc(I18N.text(fmtv(v)))')
        english = english.replace('q: f.q, category:', 'q: I18N.query(f.q), category:')
        (OUT / f"{name}.js").write_text(english, encoding="utf-8")
    for source_name, script in (("manager", "manager"), ("index", "app")):
        source = (STATIC / f"{source_name}.html").read_text(encoding="utf-8-sig")
        english = translate(source, ui).replace('lang="vi"', 'lang="en"')
        english = re.sub(rf'/static/{script}\.js\?v=[^"<]+', f'/static/en/{script}.js?v=en1', english)
        english = english.replace('/static/en-dictionary.js', '/static/en/dictionary.js')
        english = english.replace('href="/scanner"', 'href="/scanner?lang=en"').replace('href="/"', 'href="/?lang=en"')
        (OUT / f"{source_name}.html").write_text(english, encoding="utf-8")
    print("Built English dashboard, scanner, and shared display vocabulary.")


if __name__ == "__main__":
    build()
